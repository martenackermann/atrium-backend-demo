import 'dotenv/config';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { faker } from '@faker-js/faker';
import { ROLE_NAMES, type RoleName } from '@/common/domain/vocabulary';
import { initialsOf } from '@/common/domain/mappers';
import { planCoreOrg } from '@/modules/core/seed/core-org.plan';
import { seededUuidFactory } from './run-seed';

/**
 * `pnpm seed:export-users <path> [<path>...]` - writes the core seed org (52 users with the
 * same fixed UUIDs the database seed creates) as JSON for the frontend mocks
 * (SPEC_RESOLUTIONS #5). Deterministic for a given SEED_FAKER_SEED (default 4711).
 */
export function buildUsersExport(fakerSeed: number) {
  faker.seed(fakerSeed);
  const plan = planCoreOrg(faker, seededUuidFactory(faker));
  const dept = new Map(plan.departments.map((d) => [d.code, d]));
  const site = new Map(plan.sites.map((s) => [s.code, s]));
  const cc = new Map(plan.costCenters.map((c) => [c.code, c]));
  const byHandle = new Map(plan.users.map((u) => [u.handle, u]));
  const ref = (row: { id: string; code: string; name: string }) => ({ id: row.id, code: row.code, name: row.name });

  return {
    description: 'Atrium core seed org (generated by `pnpm seed:export-users`; do not edit by hand).',
    fakerSeed,
    password: 'demo1234 (demo only)',
    sites: plan.sites.map(ref),
    departments: plan.departments.map((d) => ({ ...ref(d), headId: byHandle.get(d.headHandle)!.id })),
    costCenters: plan.costCenters.map((c) => ({
      ...ref(c),
      departmentId: dept.get(c.departmentCode)!.id,
      active: true,
    })),
    users: plan.users.map((u) => {
      const hasReports = plan.users.some((other) => other.managerId === u.id && other.active);
      const effective = new Set<RoleName>(['employee', ...u.roles, ...(hasReports ? (['manager'] as const) : [])]);
      return {
        id: u.id,
        handle: u.handle,
        personaKey: u.personaKey,
        email: u.email,
        firstName: u.firstName,
        lastName: u.lastName,
        displayName: u.displayName,
        initials: initialsOf(u),
        jobTitle: u.jobTitle,
        employeeNumber: u.employeeNumber,
        phone: u.phone,
        active: u.active,
        isSiteManager: u.isSiteManager,
        /** Stored (assignable) roles. */
        assignedRoles: u.roles,
        /** Effective roles as returned by GET /me (employee + derived manager + assigned). */
        roles: ROLE_NAMES.filter((r) => effective.has(r)),
        managerId: u.managerId,
        department: ref(dept.get(u.departmentCode)!),
        site: ref(site.get(u.siteCode)!),
        costCenter: ref(cc.get(u.costCenterCode)!),
        createdAt: u.createdAt.toISOString(),
      };
    }),
  };
}

if (require.main === module) {
  const targets = process.argv.slice(2);
  if (targets.length === 0) {
    console.error('Usage: pnpm seed:export-users <path> [<path>...]');
    process.exit(1);
  }
  const data = buildUsersExport(Number(process.env.SEED_FAKER_SEED ?? 4711));
  const json = `${JSON.stringify(data, null, 2)}\n`;
  for (const target of targets) {
    const path = resolve(target);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, json);
    console.log(`[seed:export-users] ${data.users.length} users -> ${path}`);
  }
}
